// Font holds a named font and its glyph map.
type Font struct {
	Name  string
	Chars map[rune][5]string
}

// AllFonts returns all available banner fonts.
func AllFonts() []Font {
	return []Font{
		{"Block", blockFont},
		{"Shadow", shadowFont},
		{"Slim", slimFont},
		{"Dot", dotFont},
		{"Double", doubleFont},
	}
}

// Render renders text using the given font.
func Render(text string, font map[rune][5]string) string {
	text = strings.ToUpper(text)
	var lines [5]strings.Builder
	for _, ch := range text {
		glyph, ok := font[ch]
		if !ok {
			glyph = font[' ']
		}
		for i := 0; i < 5; i++ {
			lines[i].WriteString(glyph[i])
			lines[i].WriteString(" ")
		}
	}
	var sb strings.Builder
	for i := 0; i < 5; i++ {
		sb.WriteString(lines[i].String())
		if i < 4 {
			sb.WriteByte('\n')
		}
	}
	return sb.String()
}

